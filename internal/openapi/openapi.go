// Package openapi describes a tenant's HTTP API as an OpenAPI 3.1 document:
// the auth, CRUD and file endpoints it has enabled and its pipeline
// functions. Only what a client can call is listed.
package openapi

import (
	"fmt"
	"sort"
	"strings"

	"github.com/attisvalentin/supacraft/internal/pipeline"
	"github.com/attisvalentin/supacraft/internal/tenant"
)

// Options sets where the API is served.
type Options struct {
	// ServerURL is the base URL clients call; "/" when empty.
	ServerURL string
	// TenantHeader adds the X-Tenant-ID header a central server needs.
	TenantHeader string
}

type doc struct {
	cfg     *tenant.TenantConfig
	opts    Options
	paths   map[string]map[string]any
	schemas map[string]any
}

// Build returns the OpenAPI document of cfg, ready to marshal as JSON.
func Build(cfg *tenant.TenantConfig, opts Options) map[string]any {
	d := &doc{cfg: cfg, opts: opts, paths: map[string]map[string]any{}, schemas: map[string]any{
		"Error": object(map[string]any{"error": map[string]any{"type": "string"}}, "error"),
	}}
	if cfg.AuthEnabled {
		d.auth()
	}
	d.crud()
	d.files()
	d.functions()

	server := opts.ServerURL
	if server == "" {
		server = "/"
	}
	title := cfg.DisplayName
	if title == "" {
		title = cfg.DBName
	}
	out := map[string]any{
		"openapi": "3.1.0",
		"info": map[string]any{
			"title":       title,
			"version":     versionOf(cfg),
			"description": "Generated by SupaCraft from supacraft.json. Responses are wrapped in {\"data\": ...}.",
		},
		"servers":    []any{map[string]any{"url": server}},
		"paths":      d.paths,
		"components": map[string]any{"schemas": d.schemas},
	}
	if cfg.AuthEnabled {
		out["components"].(map[string]any)["securitySchemes"] = map[string]any{
			"bearerAuth": map[string]any{"type": "http", "scheme": "bearer", "bearerFormat": "JWT", "description": "The token from POST /auth/login."},
		}
	}
	return out
}

func versionOf(cfg *tenant.TenantConfig) string {
	if cfg.UpdatedAt != "" {
		return cfg.UpdatedAt
	}
	return "1"
}

// op adds an operation; tags group it in viewers.
func (d *doc) op(method, path string, operation map[string]any) {
	if d.opts.TenantHeader != "" {
		params, _ := operation["parameters"].([]any)
		operation["parameters"] = append([]any{map[string]any{
			"name": "X-Tenant-ID", "in": "header", "required": true,
			"schema": map[string]any{"type": "string", "enum": []any{d.opts.TenantHeader}},
		}}, params...)
	}
	if d.paths[path] == nil {
		d.paths[path] = map[string]any{}
	}
	d.paths[path][strings.ToLower(method)] = operation
}

// access describes an access rule and returns the operation's security
// requirement and its extra error responses.
func access(needAuth bool, roles []string) (security []any, note string) {
	if !needAuth && len(roles) == 0 {
		return []any{}, ""
	}
	note = "Requires a signed-in user."
	if len(roles) > 0 {
		note = "Requires one of the roles: " + strings.Join(roles, ", ") + "."
	}
	return []any{map[string]any{"bearerAuth": []any{}}}, note
}

func withAccess(operation map[string]any, needAuth bool, roles []string) map[string]any {
	security, note := access(needAuth, roles)
	operation["security"] = security
	responses := operation["responses"].(map[string]any)
	if note != "" {
		desc, _ := operation["description"].(string)
		operation["description"] = strings.TrimSpace(desc + " " + note)
		responses["401"] = errorResponse("No valid token.")
		if len(roles) > 0 {
			responses["403"] = errorResponse("The user's role may not use this endpoint.")
		}
	}
	return operation
}

func (d *doc) auth() {
	ep := d.cfg.APISettings.AuthEndpoints
	auth := d.cfg.APISettings.Auth
	tokens := dataResponse("Tokens.", object(map[string]any{
		"token":         map[string]any{"type": "string"},
		"refresh_token": map[string]any{"type": "string"},
		"expires_in":    map[string]any{"type": "integer", "description": "Seconds until token expires."},
	}, "token", "refresh_token", "expires_in"))
	password := map[string]any{"type": "string", "minLength": auth.MinPasswordLength(), "maxLength": tenant.MaxPasswordBytes}
	credentials := object(map[string]any{"email": map[string]any{"type": "string", "format": "email"}, "password": password}, "email", "password")

	if ep.RegisterEnabled() {
		body := object(map[string]any{"email": map[string]any{"type": "string", "format": "email"}, "password": password}, "email", "password")
		created := map[string]any{"type": "object"}
		if users := d.table("users"); users != nil {
			created = d.schemaRef(users, "")
			props := body["properties"].(map[string]any)
			for _, c := range users.Columns {
				if c.Name != "email" && c.Name != "password" && c.IsCreatable() {
					props[c.Name] = columnSchema(&c)
				}
			}
		}
		d.op("POST", "/auth/register", map[string]any{
			"tags": []any{"auth"}, "summary": "Create an account", "security": []any{},
			"requestBody": jsonBody(body),
			"responses": map[string]any{
				"201": dataResponse("The new user.", created),
				"400": errorResponse("Invalid email, password or field."),
			},
		})
	}
	if ep.LoginEnabled() {
		responses := map[string]any{"200": tokens, "401": errorResponse("Invalid credentials.")}
		if v := auth.EmailVerification; v.Enabled() && v.Required {
			responses["403"] = errorResponse("Email not verified.")
		}
		d.op("POST", "/auth/login", map[string]any{
			"tags": []any{"auth"}, "summary": "Sign in", "security": []any{},
			"requestBody": jsonBody(credentials), "responses": responses,
		})
	}
	if ep.RefreshEnabled() {
		d.op("POST", "/auth/refresh", map[string]any{
			"tags": []any{"auth"}, "summary": "Exchange a refresh token for new tokens", "security": []any{},
			"requestBody": jsonBody(object(map[string]any{"refresh_token": map[string]any{"type": "string"}}, "refresh_token")),
			"responses":   map[string]any{"200": tokens, "401": errorResponse("Invalid refresh token.")},
		})
	}
	email := jsonBody(object(map[string]any{"email": map[string]any{"type": "string", "format": "email"}}, "email"))
	token := map[string]any{"type": "string"}
	accepted := map[string]any{"202": map[string]any{"description": "Accepted, whether or not the email has an account."}}
	if auth.PasswordReset.Enabled() {
		d.op("POST", "/auth/forgot-password", map[string]any{
			"tags": []any{"auth"}, "summary": "Mail a password reset link", "security": []any{},
			"requestBody": email, "responses": accepted,
		})
		d.op("POST", "/auth/reset-password", map[string]any{
			"tags": []any{"auth"}, "summary": "Set a new password with a reset token", "security": []any{},
			"requestBody": jsonBody(object(map[string]any{"token": token, "password": password}, "token", "password")),
			"responses": map[string]any{
				"200": map[string]any{"description": "Password changed; earlier sessions end."},
				"400": errorResponse("Invalid, used or expired token, or a password that breaks the rules."),
			},
		})
	}
	if auth.EmailVerification.Enabled() {
		d.op("POST", "/auth/verify-email", map[string]any{
			"tags": []any{"auth"}, "summary": "Verify an email with its token", "security": []any{},
			"requestBody": jsonBody(object(map[string]any{"token": token}, "token")),
			"responses": map[string]any{
				"200": map[string]any{"description": "Email verified."},
				"400": errorResponse("Invalid, used or expired token."),
			},
		})
		d.op("POST", "/auth/resend-verification", map[string]any{
			"tags": []any{"auth"}, "summary": "Mail a new verification link", "security": []any{},
			"requestBody": email, "responses": accepted,
		})
	}
}

func (d *doc) table(name string) *tenant.SchemaTable {
	for i := range d.cfg.Schema.Tables {
		if d.cfg.Schema.Tables[i].Name == name {
			return &d.cfg.Schema.Tables[i]
		}
	}
	return nil
}

// crud adds /query, /create, /update and /delete for the tables that
// enable them. Each takes table_id in the body, so the request is a oneOf
// over the tables, discriminated by table_id.
func (d *doc) crud() {
	ep := d.cfg.APISettings.CRUDEndpoints
	type method struct {
		path, summary string
		enabled       bool
		settings      func(tenant.TableMethodSettings) tenant.MethodSettings
		request       func(t *tenant.SchemaTable) map[string]any
	}
	rows := func(names []string) map[string]any {
		for _, n := range names {
			d.schemaRef(d.table(n), "")
		}
		return oneOfRefs(names)
	}
	var tables []string
	for name := range d.cfg.APISettings.Tables {
		if d.table(name) != nil {
			tables = append(tables, name)
		}
	}
	sort.Strings(tables)
	where := map[string]any{"type": "object", "description": "Column filters; values or operators like {\"$gt\": 5}, {\"$in\": [...]}, {\"$like\": \"a%\"}, {\"$null\": true}."}

	methods := []method{
		{"/query", "Read rows", ep.QueryEnabled(), func(s tenant.TableMethodSettings) tenant.MethodSettings { return s.Query },
			func(t *tenant.SchemaTable) map[string]any {
				var readable []any
				for _, c := range t.Columns {
					if c.IsReadable() {
						readable = append(readable, c.Name)
					}
				}
				col := map[string]any{"type": "string", "enum": readable}
				return map[string]any{
					"select":   map[string]any{"type": "array", "items": col},
					"where":    where,
					"order_by": map[string]any{"type": "object", "additionalProperties": map[string]any{"type": "string", "enum": []any{"asc", "desc"}}},
					"limit":    map[string]any{"type": "integer", "minimum": 1, "maximum": 100, "default": 100},
					"offset":   map[string]any{"type": "integer", "minimum": 0},
					"cursor":   map[string]any{"type": "string", "description": "meta.next_cursor of the previous page."},
					"include": map[string]any{"type": "array", "description": "Related tables to attach to each row.", "items": object(map[string]any{
						"table_id": map[string]any{"type": "string"},
						"select":   map[string]any{"type": "array", "items": map[string]any{"type": "string"}},
					}, "table_id")},
				}
			}},
		{"/create", "Insert a row", ep.CreateEnabled(), func(s tenant.TableMethodSettings) tenant.MethodSettings { return s.Create },
			func(t *tenant.SchemaTable) map[string]any {
				return map[string]any{"data": d.schemaRef(t, "create")}
			}},
		{"/update", "Update rows", ep.UpdateEnabled(), func(s tenant.TableMethodSettings) tenant.MethodSettings { return s.Update },
			func(t *tenant.SchemaTable) map[string]any {
				return map[string]any{"where": where, "data": d.schemaRef(t, "update")}
			}},
		{"/delete", "Delete rows", ep.DeleteEnabled(), func(s tenant.TableMethodSettings) tenant.MethodSettings { return s.Delete },
			func(t *tenant.SchemaTable) map[string]any {
				return map[string]any{"where": where}
			}},
	}
	for _, m := range methods {
		if !m.enabled {
			continue
		}
		op := strings.TrimPrefix(m.path, "/")
		var requests, enabled []string
		mapping := map[string]any{}
		anyAuth := false
		var notes []string
		for _, name := range tables {
			s := m.settings(d.cfg.APISettings.Tables[name])
			if !s.Enabled {
				continue
			}
			t := d.table(name)
			props := m.request(t)
			props["table_id"] = map[string]any{"type": "string", "const": name}
			required := []string{"table_id"}
			if op == "create" || op == "update" {
				required = append(required, "data")
			}
			schema := object(props, required...)
			if _, note := access(s.NeedsAuth(), s.Roles); note != "" {
				schema["description"] = note
				notes = append(notes, name+": "+note)
				anyAuth = true
			}
			if s.RowPolicy != "" {
				desc, _ := schema["description"].(string)
				schema["description"] = strings.TrimSpace(desc + " Rows are limited by a row policy.")
			}
			key := name + "." + op + "_request"
			d.schemas[key] = schema
			requests = append(requests, key)
			enabled = append(enabled, name)
			mapping[name] = "#/components/schemas/" + key
		}
		if len(requests) == 0 {
			continue
		}
		body := oneOfRefs(requests)
		body["discriminator"] = map[string]any{"propertyName": "table_id", "mapping": mapping}

		var response map[string]any
		switch op {
		case "query":
			response = dataResponse("The matching rows.", map[string]any{"type": "array", "items": rows(enabled)})
			response["content"].(map[string]any)["application/json"].(map[string]any)["schema"].(map[string]any)["properties"].(map[string]any)["meta"] = object(map[string]any{
				"total":       map[string]any{"type": "integer"},
				"limit":       map[string]any{"type": "integer"},
				"offset":      map[string]any{"type": "integer"},
				"has_more":    map[string]any{"type": "boolean"},
				"next_cursor": map[string]any{"type": "string"},
			})
		case "create":
			response = dataResponse("The new row.", rows(enabled))
		case "update":
			response = dataResponse("The updated row(s).", map[string]any{})
		case "delete":
			response = dataResponse("How many rows were deleted.", object(map[string]any{"deleted": map[string]any{"type": "integer"}}, "deleted"))
		}
		status := "200"
		if op == "create" {
			status = "201"
		}
		operation := map[string]any{
			"tags": []any{"crud"}, "summary": m.summary, "operationId": op,
			"description": "table_id picks the table: " + strings.Join(enabled, ", ") + ".",
			"requestBody": jsonBody(body),
			"responses": map[string]any{
				status: response,
				"400":  errorResponse("Invalid request."),
				"404":  errorResponse("The table doesn't allow this."),
			},
		}
		if anyAuth {
			// Access differs per table; the token is optional at the
			// operation level and each request schema says when it's needed.
			operation["security"] = []any{map[string]any{}, map[string]any{"bearerAuth": []any{}}}
			operation["description"] = fmt.Sprint(operation["description"], " ", strings.Join(notes, " "))
			operation["responses"].(map[string]any)["401"] = errorResponse("No valid token for a table that requires one.")
			operation["responses"].(map[string]any)["403"] = errorResponse("The user's role may not use this table.")
		} else {
			operation["security"] = []any{}
		}
		d.op("POST", m.path, operation)
	}
}

// schemaRef adds t's row schema (kind ""), or the body of a create or
// update, on first use and returns a reference to it. Only schemas an
// endpoint uses are added, so the document shows nothing else of a table.
func (d *doc) schemaRef(t *tenant.SchemaTable, kind string) map[string]any {
	name := t.Name
	if kind != "" {
		name += "." + kind
	}
	if _, done := d.schemas[name]; !done {
		props := map[string]any{}
		var required []string
		for i := range t.Columns {
			c := &t.Columns[i]
			switch {
			case kind == "" && c.IsReadable(), kind == "update" && c.IsUpdatable():
				props[c.Name] = columnSchema(c)
			case kind == "create" && c.IsCreatable():
				props[c.Name] = columnSchema(c)
				if !c.IsNullable() && c.DefaultValue == nil && !c.Primary && !strings.EqualFold(c.Type, "primary") {
					required = append(required, c.Name)
				}
			}
		}
		d.schemas[name] = object(props, required...)
	}
	return ref(name)
}

// columnSchema maps a column type to a JSON schema.
func columnSchema(c *tenant.SchemaColumn) map[string]any {
	var s map[string]any
	switch strings.ToLower(c.Type) {
	case "primary", "uuid":
		s = map[string]any{"type": "string", "format": "uuid"}
	case "int", "bigint", "smallint", "tinyint", "bigserial":
		s = map[string]any{"type": "integer"}
	case "decimal", "numeric", "real", "double", "float":
		s = map[string]any{"type": "number"}
	case "boolean":
		s = map[string]any{"type": "boolean"}
	case "timestamp", "timestamptz":
		s = map[string]any{"type": "string", "format": "date-time"}
	case "date":
		s = map[string]any{"type": "string", "format": "date"}
	case "time":
		s = map[string]any{"type": "string", "format": "time"}
	case "json", "jsonb":
		return map[string]any{}
	case "blob", "binary", "bytea":
		s = map[string]any{"type": "string", "contentEncoding": "base64"}
	case "enum":
		values := make([]any, 0, len(c.EnumValues)+1)
		for _, v := range c.EnumValues {
			values = append(values, v)
		}
		s = map[string]any{"type": "string", "enum": values}
	default:
		s = map[string]any{"type": "string"}
	}
	if c.IsNullable() && !c.Primary && !strings.EqualFold(c.Type, "primary") {
		s["type"] = []any{s["type"], "null"}
		if e, ok := s["enum"].([]any); ok {
			s["enum"] = append(e, nil)
		}
	}
	return s
}

func (d *doc) files() {
	ep := d.cfg.APISettings.FileEndpoints
	st := d.cfg.APISettings.Storage
	if st == nil || st.Driver == "" {
		return
	}
	pathParam := []any{map[string]any{
		"name": "path", "in": "path", "required": true,
		"description": "The path returned by POST /files; it may include folders (a/b/file.png).", "schema": map[string]any{"type": "string"},
	}}
	if ep.Upload.IsEnabled() {
		upload := map[string]any{
			"tags": []any{"files"}, "summary": "Upload a file",
			"requestBody": map[string]any{"required": true, "content": map[string]any{"multipart/form-data": map[string]any{
				"schema": object(map[string]any{
					"file":   map[string]any{"type": "string", "contentMediaType": "application/octet-stream"},
					"folder": map[string]any{"type": "string", "pattern": "^[a-zA-Z0-9_-]+(/[a-zA-Z0-9_-]+)*$"},
				}, "file"),
			}}},
			"responses": map[string]any{
				"201": jsonResponse("The stored file; keep its path.", object(map[string]any{
					"path": map[string]any{"type": "string"},
					"size": map[string]any{"type": "integer"},
					"mime": map[string]any{"type": "string"},
				}, "path")),
				"400": errorResponse("Missing, too large or disallowed file."),
			},
		}
		d.op("POST", "/files", withAccess(upload, ep.Upload.AuthRequired(), ep.Upload.Roles))
	}
	if ep.Download.IsEnabled() {
		download := map[string]any{
			"tags": []any{"files"}, "summary": "Download a file", "parameters": pathParam,
			"responses": map[string]any{
				"200": map[string]any{"description": "The file.", "content": map[string]any{"application/octet-stream": map[string]any{}}},
				"404": errorResponse("File not found."),
			},
		}
		d.op("GET", "/files/{path}", withAccess(download, ep.Download.AuthRequired(), ep.Download.Roles))
	}
	if ep.Delete.IsEnabled() {
		del := map[string]any{
			"tags": []any{"files"}, "summary": "Delete a file", "parameters": pathParam,
			"responses": map[string]any{
				"200": map[string]any{"description": "Deleted."},
				"404": errorResponse("File not found."),
			},
		}
		d.op("DELETE", "/files/{path}", withAccess(del, ep.Delete.AuthRequired(), ep.Delete.Roles))
	}
}

func (d *doc) functions() {
	names := make([]string, 0, len(d.cfg.Functions))
	for name := range d.cfg.Functions {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		fn := d.cfg.Functions[name]
		method := strings.ToUpper(fn.Route.Method)
		if method == "PRIVATE" || !strings.HasPrefix(fn.Route.Path, "/fn/") {
			continue
		}
		var params []any
		pathParams, _ := pipeline.RouteParams(fn.Route.Path)
		for _, p := range pathParams {
			params = append(params, map[string]any{"name": p, "in": "path", "required": true, "schema": map[string]any{"type": "string"}})
		}
		operation := map[string]any{
			"tags": []any{"functions"}, "summary": name, "operationId": "fn_" + name,
			"responses": map[string]any{
				"200": jsonResponse("The function's response.", map[string]any{}),
			},
		}
		if len(fn.Route.Input) > 0 {
			operation["responses"].(map[string]any)["400"] = errorResponse("Invalid input; fields says which.")
		}
		fields := sortedKeys(fn.Route.Input)
		// GET takes its input from the query string, other methods from
		// the JSON body.
		if method == "GET" {
			for _, f := range fields {
				in := fn.Route.Input[f]
				params = append(params, map[string]any{"name": f, "in": "query", "required": in.Required, "schema": inputSchema(in)})
			}
			for _, p := range sortedKeys(fn.Route.URLParams) {
				if _, declared := fn.Route.Input[p]; declared {
					continue
				}
				def := fn.Route.URLParams[p]
				param := map[string]any{"name": p, "in": "query", "required": def == "", "schema": map[string]any{"type": "string"}}
				if def != "" {
					param["schema"].(map[string]any)["default"] = def
				}
				params = append(params, param)
			}
		} else if len(fields) > 0 {
			props := map[string]any{}
			var required []string
			for _, f := range fields {
				props[f] = inputSchema(fn.Route.Input[f])
				if fn.Route.Input[f].Required {
					required = append(required, f)
				}
			}
			operation["requestBody"] = jsonBody(object(props, required...))
		} else {
			operation["requestBody"] = map[string]any{"content": map[string]any{"application/json": map[string]any{"schema": map[string]any{"type": "object"}}}}
		}
		if len(params) > 0 {
			operation["parameters"] = params
		}
		d.op(method, fn.Route.Path, withAccess(operation, fn.Route.NeedsAuth(), fn.Route.Roles))
	}
}

// inputSchema maps a declared function input field to a JSON schema.
func inputSchema(in tenant.InputField) map[string]any {
	s := map[string]any{}
	if in.Type != "" && in.Type != "any" {
		s["type"] = in.Type
	}
	minKey, maxKey := "minimum", "maximum"
	switch in.Type {
	case "string":
		minKey, maxKey = "minLength", "maxLength"
	case "array":
		minKey, maxKey = "minItems", "maxItems"
	}
	if in.Min != nil {
		s[minKey] = *in.Min
	}
	if in.Max != nil {
		s[maxKey] = *in.Max
	}
	if in.Pattern != "" {
		s["pattern"] = in.Pattern
	}
	if len(in.Enum) > 0 {
		s["enum"] = in.Enum
	}
	if f := map[string]string{"email": "email", "uuid": "uuid", "date": "date", "datetime": "date-time", "url": "uri"}[in.Format]; f != "" {
		s["format"] = f
	}
	if in.Default != nil {
		s["default"] = in.Default
	}
	return s
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func object(props map[string]any, required ...string) map[string]any {
	s := map[string]any{"type": "object", "properties": props}
	if len(required) > 0 {
		s["required"] = required
	}
	return s
}

func ref(name string) map[string]any { return map[string]any{"$ref": "#/components/schemas/" + name} }

func oneOfRefs(names []string) map[string]any {
	if len(names) == 1 {
		return ref(names[0])
	}
	refs := make([]any, len(names))
	for i, n := range names {
		refs[i] = ref(n)
	}
	return map[string]any{"oneOf": refs}
}

func jsonBody(schema map[string]any) map[string]any {
	return map[string]any{"required": true, "content": map[string]any{"application/json": map[string]any{"schema": schema}}}
}

func jsonResponse(desc string, schema map[string]any) map[string]any {
	return map[string]any{"description": desc, "content": map[string]any{"application/json": map[string]any{"schema": schema}}}
}

func dataResponse(desc string, data map[string]any) map[string]any {
	return jsonResponse(desc, object(map[string]any{"data": data}, "data"))
}

func errorResponse(desc string) map[string]any { return jsonResponse(desc, ref("Error")) }
